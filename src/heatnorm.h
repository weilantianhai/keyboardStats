#pragma once
// 热力归一化（统计层）：时段峰值的拆分与按筛选模式取除数。
//
// **纯逻辑，零框架依赖**（只用到 layout.h 的键位分组判定），因此可以脱离 GUI 
// 单独编译、单独验证——像 tests/ 里其它数据层测试一样。
//
// 背景：早期实现只有一个全局峰值 g_maxKey，滚轮格数动辄上万，会把鼠标点击
// （几十次）压成一片接近零的冷色。现在峰值按组拆开，着色按当前筛选模式选用；
// 加入手柄后同理——键盘动辄上万次，会把 14 个手柄按键压成冷色。
#include "layout.h"

#include <cstdint>

namespace app {

// ── 时段峰值 ──
extern long g_maxKey;        // 全部键（含鼠标/滚轮/手柄）的最大次数：供"全部"模式跨组对比
extern long g_maxKeyboard;   // 键盘组峰值
extern long g_maxMouseClick; // 鼠标点击组峰值（左/右/中/侧键）
extern long g_maxWheel;      // 滚轮组峰值
extern long g_maxGamepad;    // 手柄组峰值

// 按键筛选：0=键盘 1=鼠标 2=手柄 3=全部 4=分开（键盘/鼠标/手柄各盒独立着色）。
// 这是**唯一**的筛选来源：热力图着色、右侧按键计数列表、直方图页的按键分布图
// 三处共用同一个值。
extern int g_keyFilter;

// 由一份时段统计的每键计数（kKeySlots 项）重算全部五个峰值。
void HeatMaximaFromCounts(const long counts[kKeySlots]);

// 某键在当前筛选模式下的热力归一化强度（0..1）。返回 0 有两种含义：
//   ① 该键在此时段内未按键；② 当前模式下该键所在组不参与着色（保持灰色）。
// 调用方把 0 交给 HeatColor()，自然落回"未按键灰"。
//
// 各模式下取的除数：
//   0 键盘：只有键盘键着色（除数=键盘组峰值），鼠标/滚轮/手柄保持灰；
//   1 鼠标：鼠标点击按点击组峰值、滚轮按滚轮组峰值着色，键盘/手柄保持灰；
//   2 手柄：只有手柄着色（除数=手柄组峰值）；
//   3 全部：键盘/鼠标/滚轮/手柄共用全局峰值（跨组对比）；
//   4 分开：四组各自独立归一（每组内部对比度拉满）——三个面板各显各的层次。
//
// 颜色反转与平方根色阶都在 HeatColor() 内部、归一化**之后**处理，
// 因此本函数与它们无关。
double HeatNorm(KeyCode vk, long count);

} // namespace app
